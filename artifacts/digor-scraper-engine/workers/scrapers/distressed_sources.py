def list_categories() -> List[Dict[str, str]]:
    return [{"key": k, **v} for k, v in CATEGORY_META.items()]


def list_sources(category: Optional[str] = None, state: Optional[str] = None) -> List[Dict[str, Any]]:
    out = SOURCES
    if category:
        out = [s for s in out if s["category"] == category]
    if state:
        s = state.upper()
        out = [src for src in out if src["state"] in (s, "*")]
    return out


def get_source(key: str) -> Optional[Dict[str, Any]]:
    for s in SOURCES:
        if s["key"] == key:
            return s
    return None


def sources_for_request(
    *, categories: Optional[List[str]] = None, state: str = "", zip_code: str = ""
) -> List[Dict[str, Any]]:
    """Resolve the set of sources for a given user request.

    If `categories` is empty, return ALL categories (filtered by state).
    """
    cats = categories or list(CATEGORY_META.keys())
    requested_state = state.upper() if state else ""
    out: List[Dict[str, Any]] = []
    for c in cats:
        out.extend(list_sources(category=c, state=requested_state))
    # Always include nationwide aggregators last
    return out


async def sources_for_request_ai(
    *,
    categories: Optional[List[str]] = None,
    state: str = "",
    county: str = "",
    city: str = "",
) -> List[Dict[str, Any]]:
    out = sources_for_request(categories=categories, state=state)
    requested_state = state.upper() if state else ""
    if requested_state and not any(src.get("state") == requested_state for src in out):
        from ..llm import suggest_distressed_sources

        for c in categories or list(CATEGORY_META.keys()):
            out.extend(await suggest_distressed_sources(state=requested_state, category=c, county=county, city=city))
    return out


